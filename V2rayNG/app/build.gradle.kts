android {
    namespace = "com.v2ray.ang"
    compileSdk = 37

    defaultConfig {
        // Amelia.Net: own package so it installs next to v2rayNG. Never change it after the
        // first public release: Android treats a new applicationId as a different app.
        applicationId = "com.ameliajustamelia.vpn"
        minSdk = 24
        targetSdk = 37
        // Bump both on every release (see RELEASING.md); the in-app updater compares versionCode.
        versionCode = 15
        versionName = "1.5.1"
        // Oldest versionCode that still works with the servers: goes to version.json as
        // minVersionCode. Older apps must update before they can connect. Raise it only when
        // a server-side change breaks old versions.
        val minVersionCode = 1
        buildConfigField("int", "MIN_VERSION_CODE", minVersionCode.toString())
        buildConfigField("String", "UPSTREAM_VERSION", "\"2.3.11\"")
        // Native dependency versions from deps.env at the repository root (CI builds exactly these)
        val deps = rootProject.file("../deps.env").takeIf { it.isFile }?.readLines().orEmpty()
            .mapNotNull { line -> line.trim().takeIf { !it.startsWith("#") && "=" in it }?.split("=", limit = 2) }
            .associate { (k, v) -> k.trim() to v.trim() }
        buildConfigField("String", "XRAY_TAG", "\"${deps["LIBV2RAY_TAG"] ?: "unknown"}\"")
        buildConfigField("String", "HEV_VERSION", "\"${deps["HEV_TAG"] ?: "unknown"}\"")

        val abiFilterList = (properties["ABI_FILTERS"] as? String)?.split(';')
        splits {
            abi {
                isEnable = true
                reset()
                if (!abiFilterList.isNullOrEmpty()) {
                    include(*abiFilterList.toTypedArray())
                } else {
                    include(
                        "arm64-v8a",
                        "armeabi-v7a",
                        "x86_64",
                        "x86"
                    )
                }
                isUniversalApk = abiFilterList.isNullOrEmpty()
            }
        }

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
        }
    }

    flavorDimensions.add("distribution")
    productFlavors {
        create("fdroid") {
            dimension = "distribution"
            applicationIdSuffix = ".fdroid"
            buildConfigField("String", "DISTRIBUTION", "\"F-Droid\"")
        }
        create("playstore") {
            dimension = "distribution"
            buildConfigField("String", "DISTRIBUTION", "\"Play Store\"")
        }
    }

    sourceSets {
        getByName("main") {
            jniLibs.srcDirs("libs")
        }
    }

    compileOptions {
        isCoreLibraryDesugaringEnabled = true
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlin {
        compilerOptions {
            jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17)
        }
    }

    applicationVariants.all {
        val variant = this
        val isFdroid = variant.productFlavors.any { it.name == "fdroid" }
        if (isFdroid) {
            val versionCodes =
                mapOf(
                    "armeabi-v7a" to 2, "arm64-v8a" to 1, "x86" to 4, "x86_64" to 3, "universal" to 0
                )

            variant.outputs
                .map { it as com.android.build.gradle.internal.api.ApkVariantOutputImpl }
                .forEach { output ->
                    val abi = output.getFilter("ABI") ?: "universal"
                    output.outputFileName = "AmeliaNet_${variant.versionName}-fdroid_${abi}.apk"
                    if (versionCodes.containsKey(abi)) {
                        output.versionCodeOverride =
                            (100 * variant.versionCode + versionCodes[abi]!!).plus(5000000)
                    } else {
                        return@forEach
                    }
                }
        } else {
            // Amelia.Net: every ABI split and the universal APK share one versionCode, so the
            // updater can install any of them over any other.
            variant.outputs
                .map { it as com.android.build.gradle.internal.api.ApkVariantOutputImpl }
                .forEach { output ->
                    val abi = output.getFilter("ABI") ?: "universal"
                    output.outputFileName = "AmeliaNet_${variant.versionName}_${abi}.apk"
                }
        }
    }

    buildFeatures {
        buildConfig = true
        compose = true
    }

    androidResources {
        generateLocaleConfig = true
        localeFilters += listOf(
